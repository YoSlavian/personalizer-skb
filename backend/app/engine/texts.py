"""Тексты предложений: один продукт — разные аргументы для собственника, ФД и бухгалтера.

Тон Альфа-Банка: профессионально, современно, понятно. Тексты ВЭД проходят проверку на соответствие
валютному законодательству до запуска (в прототипе — статичные согласованные формулировки).
"""

from app.engine.catalog import INDUSTRIES
from app.engine.profile import ClientProfile
from app.engine.rules import RulesConfig

Text = tuple[str, str, str]  # заголовок, текст, кнопка


def text_for(code: str, role: str | None, p: ClientProfile, cfg: RulesConfig, *, entities: int | None = None) -> Text:
    n = p.weeks_to_peak
    season = p.seasonal and n <= cfg.momentum.season_window_max and INDUSTRIES[p.industry].seasonal
    neutral = role is None

    if code == "working":
        if neutral:
            return ("Оборотный кредит для вашего бизнеса", "Финансирование текущих закупок. Рассчитайте условия в калькуляторе.", "Рассчитать условия")
        if role == "owner":
            return (
                "Закупки к сезону без отвлечения денег из развития" if season else "Рост без кассовых разрывов",
                f"До пика закупок {n} нед. Оборотный кредит под обороты вашей компании, чтобы деньги на развитие остались в бизнесе."
                if season
                else "Оборотный кредит под обороты компании: текущие закупки не тормозят развитие.",
                "Рассчитать условия",
            )
        return (
            "Ликвидность к сезону закупок" if season else "Оборотные средства под ваш денежный поток",
            f"До пика закупок {n} нед. Подберём лимит и график погашения под поступления после сезона."
            if season
            else "Лимит под обороты компании, график погашения под поступления от клиентов.",
            "Рассчитать лимит",
        )
    if code == "concession":
        return ("Льготное финансирование", "Проверим, подходит ли компания под программу льготного кредитования, и рассчитаем условия.", "Проверить условия")
    if code == "project":
        if neutral:
            return ("Финансирование проектов", "Кредит на новые мощности и инвестиции.", "Обсудить проект")
        return ("Финансирование развития", "Проектный кредит на новые мощности и инвестиции: обсудим проект с менеджером.", "Обсудить проект")
    if code == "leasing":
        if role == "fd":
            return ("Лизинг вместо крупной разовой покупки", "Платежи распределены по сроку, нагрузка на ликвидность ниже.", "Рассчитать лизинг")
        return ("Техника и транспорт в лизинг", "Обновите парк без единовременных затрат: подберём условия под ваш бизнес.", "Рассчитать лизинг")
    if code == "factoring":
        return ("Поставки с отсрочкой без кассовых разрывов", "Факторинг: получайте деньги по поставке, не дожидаясь оплаты покупателя.", "Узнать условия")
    if code == "ved":
        if role in ("acc", "ops"):
            return ("Документы валютного контроля без лишних шагов", "Подскажем, какие документы нужны по этому платежу, и проверим их до отправки.", "Открыть валютный контроль")
        return ("Валютный платёж под контролем", "Конвертация и валютный контроль в одном окне, рядом с валютным переводом.", "Перейти к конвертации")
    if code == "deposit":
        if p.deposit_ending:
            return ("Продлите депозит без перерыва", "Срок депозита скоро закончится: продлите его в пару кликов или выберите новый срок.", "Продлить депозит")
        if role == "owner":
            return ("Доход на свободные деньги компании", "Разместите временно свободные средства и сохраните доступ к ликвидности.", "Выбрать срок")
        return ("Свободные остатки работают", "Разместите временно свободные средства на удобный срок, сохранив доступ к ликвидности.", "Выбрать срок")
    if code == "digital":
        if role == "ops":
            return ("Платежи без ручного ввода", "Шаблоны и импорт платежей: меньше ручной работы каждый день.", "Настроить")
        return ("Банк и учётная система без ручного переноса", "Выписки и платежи синхронизируются с учётной системой: меньше ручной работы для бухгалтерии.", "Подключить интеграцию")
    if code == "pool":
        who = f"{entities} компании" if entities else "компании группы"
        return (
            "Единый остаток для всей группы",
            f"Свободные деньги одной компании закрывают потребность другой: {who} под одним управлением, меньше процентов по кредитам внутри группы.",
            "Обсудить с менеджером",
        )
    if code == "glimit":
        return ("Один лимит на всю группу", "Общий кредитный лимит, который компании группы используют по мере потребности.", "Обсудить с менеджером")
    if code == "syndic":
        return ("Крупное финансирование для группы", "Синдицированный кредит или выпуск облигаций: обсудим структуру сделки с менеджером.", "Обсудить сделку")
    raise KeyError(code)
